  /** 받침에 맞춰 조사 붙이기: josa("마음 나눔", "이", "가") → "마음 나눔이", josa("끈기", "이", "가") → "끈기가" (앱 String.josa 와 같아요) */
  function josa(s, withBatchim, without) {
    s = String(s == null ? '' : s);
    var chars = Array.from(s);
    var c = chars.length ? chars[chars.length - 1].codePointAt(0) : 0;
    if (!(c >= 0xAC00 && c <= 0xD7A3)) return s + without;
    return s + ((c - 0xAC00) % 28 === 0 ? without : withBatchim);
  }

