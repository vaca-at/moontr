  /** 9가지 유형 날개: 가장 높은 번호의 양옆(9 옆은 1) 가운데 점수가 더 높은 쪽 (같으면 작은 번호) — 앱 Bank.nineWing 과 같아요 */
  function nineWing(s) { if (!s || s.length !== 9) return 0; var t = Score.top(s), a = (t + 8) % 9, b = (t + 1) % 9; return (s[a] > s[b] || (s[a] === s[b] && a < b)) ? a : b; }
