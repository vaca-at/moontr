  /** 닮은 점 · 다른 점 글에 쓰는 관계 (0 = 부모와 아이 · 선생님과 학생, 1 = 부부 · 동료) */
  function relOf(member) { var r = member && member.role; return r === 'partner' || r === 'coworker' ? 1 : 0; }
  function whoWord(rel) { return rel === 0 ? '아이' : '배우자'; }
  function caseOf(me, other) {
    if (me >= 60 && other >= 60) return 0;
    if (me < 40 && other < 40) return 1;
    if (me - other >= 25) return 2;
    if (other - me >= 25) return 3;
    return 4;
  }
  function matchTemper(scale, me, other, rel) {
    var s = clamp(scale, 0, D.matchTemperText.length - 1);
    return D.matchTemperText[s][caseOf(me, other)].split('{w}').join(whoWord(rel));
  }
  function matchType(axis, same, rel) {
    var a = clamp(axis, 0, D.matchTypeText.length - 1);
    return D.matchTypeText[a][same ? 0 : 1].split('{w}').join(whoWord(rel));
  }
  /** 전체 한 줄 총평. gap = 기질 4척도 점수 차이의 합 (0~400) */
  function matchSummary(gap, rel) {
    var w = whoWord(rel);
    if (gap < 80) return '나와 ' + w + '는 마음의 결이 많이 닮았어요. 서로를 쉽게 이해하는 만큼, 둘 다 놓치는 부분은 함께 챙겨 보세요.';
    if (gap < 160) return '나와 ' + w + '는 닮은 점과 다른 점이 골고루 있어요. 다른 점은 서로를 채워 주는 힘이 될 수 있어요.';
    return '나와 ' + w + '는 다른 점이 많아서 서로에게 없는 것을 줄 수 있어요. 차이를 알아 두면 부딪힘이 줄어요.';
  }
  function discMatch(a, b, rel) {
    var x = clamp(a, 0, 3), y = clamp(b, 0, 3), r = rel === 0 ? 0 : 1;
    return D.discMatchText[x][y].split('{w}').join(whoWord(r)) + ' ' + D.discMatchTip[r][y];
  }
  function mindMatch(scale, me, other, rel) {
    var s = clamp(scale, 0, D.mindMatchText.length - 1);
    return D.mindMatchText[s][caseOf(me, other)].split('{w}').join(whoWord(rel));
  }

  /**
   * meResults = 나의 결과 목록, otherResults = 그 사람의 결과 목록, member = { name, role }
   * 검사마다 가장 최근 결과로 견줘요 (at 이 있으면 가장 늦은 것, 없으면 목록 맨 뒤)
   */
  function match(meResults, otherResults, member) {
    member = member || { name: '', role: '' };
    var name = member.name || '';
    var rel = relOf(member);
    /** 학생 · 동료는 글 속 '아이' · '배우자'를 바꿔 불러요 */
    function fit(s) {
      if (member.role === 'student') return s.split('아이').join('학생');
      if (member.role === 'coworker') return s.split('배우자').join('동료');
      return s;
    }
    function r(kind, mine) { return latestOf(mine ? meResults : otherResults, kind); }
    var pairs = [['temper', '타고난 기질'], ['type16', '16가지 성격 유형'], ['mind', '마음 결'], ['disc', '행동 스타일']];
    var out = { title: '나와 ' + name + ' 닮은 점 · 다른 점', head: '나 × ' + name, missing: null, sections: [],
      foot: "좋고 나쁨이 아니라 '어디가 닮고 어디가 다른지'예요. 다른 점은 서로를 채워 주는 자리이기도 해요." };

    if (!pairs.some(function (p) { return r(p[0], true) && r(p[0], false); })) {
      out.missing = { h: '닮은 점 · 다른 점을 보려면 같은 검사를 둘 다 해야 해요',
        lines: pairs.map(function (p) { return '· ' + p[1] + ': 나 ' + (r(p[0], true) ? '했어요' : '아직') + ' / ' + name + ' ' + (r(p[0], false) ? '했어요' : '아직'); }) };
    }
    var a, b;
    if ((a = r('temper', true)) && (b = r('temper', false))) {
      var x = (a.scores || []).slice(0, 4), y = (b.scores || []).slice(0, 4), gap = 0;
      for (var i = 0; i < Math.min(x.length, y.length); i++) gap += Math.abs(x[i] - y[i]);
      var rows = [];
      for (var j = 0; j < Math.min(4, x.length, y.length); j++) {
        rows.push({ name: TEMPER_NAMES[j], me: x[j], other: y[j], text: fit(matchTemper(j, x[j], y[j], rel)) });
      }
      out.sections.push({ kind: 'temper', h: '타고난 기질', summary: fit(matchSummary(gap, rel)), rows: rows });
    }
    if ((a = r('type16', true)) && (b = r('type16', false)) && a.code && b.code && a.code.length === 4 && b.code.length === 4) {
      var trows = [];
      for (var ax = 0; ax < 4; ax++) {
        var cx = a.code[ax], cy = b.code[ax];
        trows.push({ label: AX[ax].title + ' · ' + cx + ' ' + (cx === cy ? '=' : '≠') + ' ' + cy, same: cx === cy, text: fit(matchType(ax, cx === cy, rel)) });
      }
      out.sections.push({ kind: 'type16', h: '16가지 유형 · 나 ' + a.code + ' × ' + name + ' ' + b.code, rows: trows });
    }
    if ((a = r('mind', true)) && (b = r('mind', false)) && a.scores && b.scores && a.scores.length === 6 && b.scores.length === 6) {
      var mrows = [];
      for (var m = 0; m < 6; m++) mrows.push({ name: MIND.kinds[m], me: a.scores[m], other: b.scores[m], text: fit(mindMatch(m, a.scores[m], b.scores[m], rel)) });
      out.sections.push({ kind: 'mind', h: '마음 결 · 나 ' + MIND.kinds[Score.top(a.scores)] + ' × ' + name + ' ' + MIND.kinds[Score.top(b.scores)], rows: mrows });
    }
    if ((a = r('disc', true)) && (b = r('disc', false)) && a.scores && b.scores && a.scores.length === 4 && b.scores.length === 4) {
      var dx = Score.top(a.scores), dy = Score.top(b.scores);
      out.sections.push({ kind: 'disc', h: '행동 스타일 · 나 ' + D.discNames[dx] + ' × ' + name + ' ' + D.discNames[dy], text: fit(discMatch(dx, dy, rel)) });
    }
    return out;
  }

