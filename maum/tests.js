  /** 결과 목록에서 이 검사의 가장 최근 것 (at 이 있으면 가장 늦은 것, 없으면 목록 맨 뒤) */
  function latestOf(list, kind, who) {
    if (!Array.isArray(list)) return null;
    var best = null, bestAt = -Infinity, bestIdx = -1;
    list.forEach(function (r, i) {
      if (!r || r.kind !== kind) return;
      if (who != null && r.who != null && r.who !== who) return;
      var t = atMs(r);
      var key = t == null ? i : t;
      if (best === null || key > bestAt || (key === bestAt && i > bestIdx)) { best = r; bestAt = key; bestIdx = i; }
    });
    return best;
  }

