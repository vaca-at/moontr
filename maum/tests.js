  var Score = {
    /** 1~5 답 + 거꾸로 문항 → 0~100 */
    likert: function (answers, scaleOf, rev, n) {
      var sum = [], cnt = [], i;
      for (i = 0; i < n; i++) { sum.push(0); cnt.push(0); }
      for (i = 0; i < answers.length; i++) {
        var a = answers[i];
        if (!(a > 0) || i >= scaleOf.length) continue;
        sum[scaleOf[i]] += rev[i] ? 6 - a : a; cnt[scaleOf[i]] += 1;
      }
      var out = [];
      for (i = 0; i < n; i++) out.push(cnt[i] === 0 ? 50 : Math.round((sum[i] / cnt[i] - 1) / 4 * 100));
      return out;
    },
    /** 고르기(0 = 앞 글자) → 축마다 앞 글자 % · 네 글자 */
    type16: function (picks, axes) {
      var a = [0, 0, 0, 0], n = [0, 0, 0, 0], i;
      for (i = 0; i < picks.length; i++) {
        if (i >= axes.length) continue;
        n[axes[i]] += 1; if (picks[i] === 0) a[axes[i]] += 1;
      }
      var pct = [], code = '';
      for (i = 0; i < 4; i++) pct.push(n[i] === 0 ? 50 : Math.round(a[i] / n[i] * 100));
      for (i = 0; i < 4; i++) code += pct[i] >= 50 ? AX[i].first : AX[i].second;
      return { pct: pct, code: code };
    },
    /** 가장 높은 것의 번호 (같으면 앞 번호) */
    top: function (s) {
      var b = 0;
      for (var i = 1; i < s.length; i++) if (s[i] > s[b]) b = i;
      return b;
    },
    /** 두 결과가 얼마나 비슷한지 0~100 (척도 점수 차이의 평균으로) */
    similar: function (a, b) {
      var n = Math.min(a.length, b.length);
      if (n <= 0) return 0;
      var sum = 0;
      for (var i = 0; i < n; i++) sum += Math.abs(a[i] - b[i]);
      return Math.max(0, 100 - Math.floor(sum / n));
    },
  };

