  /** 날짜 꺼내기 (Date · 숫자(ms) · 글 · Firestore Timestamp 모두 받아요) */
  function toDate(at) {
    if (at == null) return null;
    if (at instanceof Date) return isNaN(at) ? null : at;
    if (typeof at.toDate === 'function') return at.toDate();
    if (typeof at === 'object' && isNum(at.seconds)) return new Date(at.seconds * 1000);
    var d = new Date(at);
    return isNaN(d) ? null : d;
  }
